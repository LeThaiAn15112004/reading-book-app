#!/usr/bin/env node
// Spec 009 T051 (research R6): which `node_modules` folders the Desktop package may contain.
//
//   node source/scripts/desktop-package-deps.mjs           # check: fails when electron-builder.json5 is stale
//   node source/scripts/desktop-package-deps.mjs --write   # rewrite the generated block in electron-builder.json5
//   node source/scripts/desktop-package-deps.mjs --list    # print the folders
//
// One manifest carries Desktop AND Mobile dependencies, so electron-builder's default (every production dependency)
// would ship Expo and React Native in the installer (FR-017). Everything the app needs is bundled by Vite into `dist/`
// and `dist-electron/`, except Main's externals (`vite.config.ts` `rollupOptions.external`), which Main loads from
// `node_modules` at run time. electron-builder.json5 therefore excludes `node_modules/**` and lists exactly those
// externals and their runtime dependencies, as resolved by `npm ls --omit=dev --all`.
//
// Platform-specific optional packages (sharp's `@img/sharp-<os>-<arch>`, …) are listed by name even when they are
// not installed here, so the block is the same on every OS; a pattern that matches nothing packages nothing.
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const BUILDER_CONFIG = path.join(repoRoot, 'electron-builder.json5')

/** Main's externals: keep in step with `rollupOptions.external` of the Main build in vite.config.ts. */
export const MAIN_EXTERNALS = [
  'better-sqlite3',
  '@huggingface/transformers',
  'onnxruntime-node',
  'sharp',
  'music-metadata',
  'pdfjs-dist',
]

export const BEGIN_MARKER = '// BEGIN main externals (generated by source/scripts/desktop-package-deps.mjs --write)'
export const END_MARKER = '// END main externals'

function npmLsTree() {
  let out
  try {
    out = execFileSync('npm', ['ls', '--omit=dev', '--all', '--json', '--long'], {
      cwd: repoRoot,
      encoding: 'utf8',
      maxBuffer: 256 * 1024 * 1024,
      shell: process.platform === 'win32',
      stdio: ['ignore', 'pipe', 'ignore'],
    })
  } catch (error) {
    // `npm ls` exits 1 on extraneous / invalid entries elsewhere in the tree but still prints the whole tree.
    out = error.stdout
    if (!out) throw error
  }
  return JSON.parse(out)
}

const toRel = (p) => path.relative(repoRoot, p).replaceAll('\\', '/')

/** Package folders (relative to the root) that Main's externals need at run time. */
export function resolveFolders(tree = npmLsTree()) {
  // `npm ls` prints a package's children only at one place in the tree; every other place is a "deduped" leaf with
  // the same path. Index each path by the entry that carries its children.
  const byPath = new Map()
  const index = (node) => {
    for (const child of Object.values(node.dependencies ?? {})) {
      if (!child?.path) continue
      const known = byPath.get(child.path)
      if (known && Object.keys(known.dependencies ?? {}).length >= Object.keys(child.dependencies ?? {}).length) continue
      byPath.set(child.path, child)
      index(child)
    }
  }
  index(tree)

  const folders = new Set()
  const seen = new Set()
  const walk = (entry) => {
    const node = entry?.path ? byPath.get(entry.path) ?? entry : entry
    if (!node || !node.path || seen.has(node.path)) return
    seen.add(node.path)
    folders.add(toRel(node.path))
    for (const [name, child] of Object.entries(node.dependencies ?? {})) {
      if (child && child.path) walk(child)
      else if (child && child.missing !== true) folders.add(`node_modules/${name}`)
    }
    // Optional dependencies of another platform: not installed here, listed by their hoisted name.
    for (const name of Object.keys(node.optionalDependencies ?? {})) {
      if (!node.dependencies?.[name]?.path) folders.add(`node_modules/${name}`)
    }
  }
  for (const name of MAIN_EXTERNALS) {
    const node = tree.dependencies?.[name]
    if (node?.path) walk(node)
    else if (!['onnxruntime-node', 'sharp'].includes(name)) {
      // onnxruntime-node and sharp are reached through @huggingface/transformers; the others are direct dependencies.
      throw new Error(`Main external "${name}" is not installed as a production dependency`)
    }
  }
  // A folder inside another listed folder is already covered by that folder's pattern.
  const sorted = [...folders].sort()
  return sorted.filter((f) => !sorted.some((other) => other !== f && f.startsWith(`${other}/`)))
}

export function renderBlock(folders, indent = '    ') {
  return [
    `${indent}${BEGIN_MARKER}`,
    ...folders.map((f) => `${indent}"${f}/**",`),
    `${indent}${END_MARKER}`,
  ].join('\n')
}

function replaceBlock(config, block) {
  const begin = config.indexOf(BEGIN_MARKER)
  const end = config.indexOf(END_MARKER)
  if (begin < 0 || end < begin) throw new Error(`electron-builder.json5 has no "${BEGIN_MARKER}" … "${END_MARKER}" block`)
  const lineStart = config.lastIndexOf('\n', begin) + 1
  const lineEnd = config.indexOf('\n', end)
  return config.slice(0, lineStart) + block + config.slice(lineEnd < 0 ? config.length : lineEnd)
}

function main() {
  const args = new Set(process.argv.slice(2))
  const folders = resolveFolders()
  if (args.has('--list')) {
    console.log(folders.join('\n'))
    return
  }
  if (!existsSync(BUILDER_CONFIG)) throw new Error('electron-builder.json5 not found at the repository root')
  // Compare with LF only: a Windows checkout (core.autocrlf) has CRLF, which is not a difference in the allowlist.
  const raw = readFileSync(BUILDER_CONFIG, 'utf8')
  const eol = raw.includes('\r\n') ? '\r\n' : '\n'
  const current = raw.replaceAll('\r\n', '\n')
  const next = replaceBlock(current, renderBlock(folders))
  if (args.has('--write')) {
    if (next !== current) writeFileSync(BUILDER_CONFIG, next.replaceAll('\n', eol))
    console.log(`electron-builder.json5: ${folders.length} node_modules folders for Main's externals${next === current ? ' (unchanged)' : ' (updated)'}`)
    return
  }
  if (next !== current) {
    console.error(
      'electron-builder.json5: the node_modules allowlist does not match `npm ls` for Main\'s externals.\n' +
        'Run `node source/scripts/desktop-package-deps.mjs --write` and commit the result.',
    )
    process.exit(1)
  }
  console.log(`electron-builder.json5: node_modules allowlist up to date (${folders.length} folders)`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main()
  } catch (error) {
    console.error(error instanceof Error ? error.message : error)
    process.exit(1)
  }
}
