#!/usr/bin/env node
// Spec 009 T051 (research R6): which `node_modules` folders the Desktop package may contain.
//
//   node source/scripts/desktop-package-deps.mjs           # check: fails when electron-builder.json5 is stale
//   node source/scripts/desktop-package-deps.mjs --write   # rewrite the generated block in electron-builder.json5
//   node source/scripts/desktop-package-deps.mjs --list    # print the folders
//
// One manifest carries Desktop AND Mobile dependencies, so electron-builder's default (every production dependency)
// would ship Expo and React Native in the installer (FR-017). Everything the app needs is bundled by Vite into `dist/`
// and `dist-electron/`, except Main's externals (`vite.config.ts` `rollupOptions.external`), which Main loads from
// `node_modules` at run time. electron-builder.json5 therefore excludes `node_modules/**` and lists exactly those
// externals and their runtime dependencies.
//
// The paths are the ones INSIDE THE PACKAGE, not the ones on disk: electron-builder (>= 26) collects the production
// graph of the whole manifest with its own collector and re-hoists it, and the `files` patterns are matched against
// that destination path (`stat.moduleFullFilePath` in app-builder-lib's filter). A package npm nested on disk can land
// elsewhere in the package (onnxruntime-node/node_modules/global-agent → node_modules/global-agent; the package's
// top-level semver is react-native's semver@7). An allowlist written in disk paths (`npm ls`) silently dropped those
// packages, and the installed app could not load @huggingface/transformers ("Cannot find package 'semver' imported
// from …/sharp/dist/libvips.mjs" → Translate MODEL_LOAD_FAILED in every format). So this script runs electron-builder's
// own collector and resolves every runtime dependency with Node's lookup in that destination layout.
//
// Platform-specific optional packages (sharp's `@img/sharp-<os>-<arch>`, …) are listed by name even when they are
// not installed here, so the block is the same on every OS; a pattern that matches nothing packages nothing.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const BUILDER_CONFIG = path.join(repoRoot, 'electron-builder.json5')

/** Main's externals: keep in step with `rollupOptions.external` of the Main build in vite.config.ts. */
export const MAIN_EXTERNALS = [
  'better-sqlite3',
  '@huggingface/transformers',
  'onnxruntime-node',
  'sharp',
  'music-metadata',
  'pdfjs-dist',
]

export const BEGIN_MARKER = '// BEGIN main externals (generated by source/scripts/desktop-package-deps.mjs --write)'
export const END_MARKER = '// END main externals'

/**
 * electron-builder's collected module tree, i.e. the layout it packages: `{ name, dir, dependencies? }` where nested
 * `dependencies` go into the parent's own node_modules. `app-builder-lib/out/node-module-collector` is internal:
 * re-check after an electron-builder upgrade (check:desktop-package's packaged runtime check catches a drift).
 */
export async function collectPackagedTree() {
  const require = createRequire(path.join(repoRoot, 'package.json'))
  const { getCollectorByPackageManager, PM } = require('app-builder-lib/out/node-module-collector')
  const { TmpDir } = require('temp-file')
  const tmp = new TmpDir('desktop-package-deps')
  try {
    const name = JSON.parse(readFileSync(path.join(repoRoot, 'package.json'), 'utf8')).name
    const { nodeModules } = await getCollectorByPackageManager(PM.NPM, repoRoot, tmp).getNodeModules({ packageName: name })
    return nodeModules
  } finally {
    await tmp.cleanup()
  }
}

/** Destination folder in the package (`node_modules/...`) → its source folder on disk, for every collected module. */
export function indexTree(tree) {
  const byDest = new Map()
  const visit = (list, parentDest) => {
    for (const m of list ?? []) {
      const dest = parentDest ? `${parentDest}/node_modules/${m.name}` : `node_modules/${m.name}`
      byDest.set(dest, m.dir)
      visit(m.dependencies, dest)
    }
  }
  visit(tree, '')
  return byDest
}

/** Node's lookup of `name` from the package at `dest` ('' = the app), in the destination layout. */
function resolveFrom(byDest, dest, name) {
  let base = dest
  while (base) {
    const candidate = `${base}/node_modules/${name}`
    if (byDest.has(candidate)) return candidate
    const i = base.lastIndexOf('/node_modules/')
    base = i < 0 ? '' : base.slice(0, i)
  }
  const top = `node_modules/${name}`
  return byDest.has(top) ? top : null
}

const readManifestOnDisk = (dir) => JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8'))

/**
 * Packaged node_modules folders that Main's externals need at run time: `folders` = the allowlist (incl. other
 * platforms' optional packages), `installed` = the ones collected here (each must be in app.asar with its package.json).
 */
export function resolvePackaged(tree, readManifest = readManifestOnDisk) {
  const byDest = indexTree(tree)
  const installed = new Set()
  const notInstalled = new Set()
  const queue = []
  for (const name of MAIN_EXTERNALS) {
    const dest = resolveFrom(byDest, '', name)
    if (!dest) throw new Error(`Main external "${name}" is not in electron-builder's production dependency tree`)
    queue.push(dest)
  }
  while (queue.length > 0) {
    const dest = queue.pop()
    if (installed.has(dest)) continue
    installed.add(dest)
    const manifest = readManifest(byDest.get(dest))
    const optional = new Set([
      ...Object.keys(manifest.optionalDependencies ?? {}),
      ...Object.entries(manifest.peerDependenciesMeta ?? {}).filter(([, meta]) => meta?.optional).map(([n]) => n),
    ])
    const names = new Set([
      ...Object.keys(manifest.dependencies ?? {}),
      ...Object.keys(manifest.optionalDependencies ?? {}),
      ...Object.keys(manifest.peerDependencies ?? {}),
    ])
    for (const name of names) {
      const found = resolveFrom(byDest, dest, name)
      if (found) queue.push(found)
      else if (optional.has(name)) notInstalled.add(`node_modules/${name}`) // another platform's package
      else throw new Error(`"${name}" (needed by ${dest}) is not in electron-builder's production dependency tree`)
    }
  }
  // A folder inside another listed folder is covered by that folder's `/**` pattern (the match is on the destination
  // path, nested node_modules included); a nested package is still listed so the block shows it.
  const all = [...new Set([...installed, ...notInstalled])].sort()
  const isNestedPackage = (f, other) => f.slice(other.length + 1).includes('node_modules/')
  const folders = all.filter((f) => !all.some((other) => other !== f && f.startsWith(`${other}/`) && !isNestedPackage(f, other)))
  return { folders, installed: [...installed].sort() }
}

/** Package folders (relative, inside the package) that Main's externals need at run time. */
export async function resolveFolders() {
  return resolvePackaged(await collectPackagedTree()).folders
}

export function renderBlock(folders, indent = '    ') {
  return [
    `${indent}${BEGIN_MARKER}`,
    ...folders.map((f) => `${indent}"${f}/**",`),
    `${indent}${END_MARKER}`,
  ].join('\n')
}

function replaceBlock(config, block) {
  const begin = config.indexOf(BEGIN_MARKER)
  const end = config.indexOf(END_MARKER)
  if (begin < 0 || end < begin) throw new Error(`electron-builder.json5 has no "${BEGIN_MARKER}" … "${END_MARKER}" block`)
  const lineStart = config.lastIndexOf('\n', begin) + 1
  const lineEnd = config.indexOf('\n', end)
  return config.slice(0, lineStart) + block + config.slice(lineEnd < 0 ? config.length : lineEnd)
}

async function main() {
  const args = new Set(process.argv.slice(2))
  const folders = await resolveFolders()
  if (args.has('--list')) {
    console.log(folders.join('\n'))
    return
  }
  if (!existsSync(BUILDER_CONFIG)) throw new Error('electron-builder.json5 not found at the repository root')
  // Compare with LF only: a Windows checkout (core.autocrlf) has CRLF, which is not a difference in the allowlist.
  const raw = readFileSync(BUILDER_CONFIG, 'utf8')
  const eol = raw.includes('\r\n') ? '\r\n' : '\n'
  const current = raw.replaceAll('\r\n', '\n')
  const next = replaceBlock(current, renderBlock(folders))
  if (args.has('--write')) {
    if (next !== current) writeFileSync(BUILDER_CONFIG, next.replaceAll('\n', eol))
    console.log(`electron-builder.json5: ${folders.length} node_modules folders for Main's externals${next === current ? ' (unchanged)' : ' (updated)'}`)
    return
  }
  if (next !== current) {
    console.error(
      "electron-builder.json5: the node_modules allowlist does not match electron-builder's packaged layout for Main's externals.\n" +
        'Run `node source/scripts/desktop-package-deps.mjs --write` and commit the result.',
    )
    process.exit(1)
  }
  console.log(`electron-builder.json5: node_modules allowlist up to date (${folders.length} folders)`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error)
    process.exit(1)
  })
}
